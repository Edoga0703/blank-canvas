export function translateMaster(
  language: SupportedLanguage,
  ptText: string,
  params?: Record<string, string | number>,
): string {
  let raw = ptText;
  if (language !== "pt") {
    const entry = MASTER_STRINGS[ptText];
    if (entry) {
      raw = entry[language] || ptText;
    }
  }
  if (params) {
    for (const [k, v] of Object.entries(params)) {
      raw = raw.replace(new RegExp(`\\{${k}\\}`, "g"), String(v));
    }
  }
  return raw;
}

export function useMasterT() {
  const { language, localeCode } = useLanguage();
  const mt = useCallback(
    (ptText: string, params?: Record<string, string | number>) =>
      translateMaster(language, ptText, params),
    [language],
  );
  return { mt, language, localeCode };
}
